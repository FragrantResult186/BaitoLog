-- テーブル作成（UserDao / StudentDao / SchoolClassDao が使うテーブル名・列名に合わせてある）
-- 学生と教職員は USERS に共通項目を持ち、STUDENT / TEACHER に学校などを持つ

CREATE TABLE IF NOT EXISTS SCHOOL (
    ID                 INT          GENERATED BY DEFAULT AS IDENTITY,
    CODE               VARCHAR(10)  NOT NULL UNIQUE,
    NAME               VARCHAR(30)  NOT NULL,
    NORMAL_LIMIT_HOURS DOUBLE       NOT NULL DEFAULT 28,
    PRIMARY KEY (ID)
);

CREATE TABLE IF NOT EXISTS SCHOOL_CLASS (
    ID        INT         GENERATED BY DEFAULT AS IDENTITY,
    SCHOOL_ID INT         NOT NULL,
    NAME      VARCHAR(10) NOT NULL,
    PRIMARY KEY (ID),
    UNIQUE (SCHOOL_ID, NAME),
    FOREIGN KEY (SCHOOL_ID) REFERENCES SCHOOL (ID)
);

CREATE TABLE IF NOT EXISTS USERS (
    ID                   INT          GENERATED BY DEFAULT AS IDENTITY,
    LOGIN_ID             VARCHAR(20)  NOT NULL UNIQUE,
    PASSWORD             VARCHAR(64)  NOT NULL,
    NAME                 VARCHAR(30)  NOT NULL,
    ROLE                 VARCHAR(10)  NOT NULL,
    PASSWORD_INITIALIZED BOOLEAN      NOT NULL DEFAULT FALSE,
    IS_ACTIVE            BOOLEAN      NOT NULL DEFAULT TRUE,
    PRIMARY KEY (ID)
);

CREATE TABLE IF NOT EXISTS STUDENT (
    USER_ID   INT NOT NULL,
    SCHOOL_ID INT NOT NULL,
    PRIMARY KEY (USER_ID),
    FOREIGN KEY (USER_ID) REFERENCES USERS (ID),
    FOREIGN KEY (SCHOOL_ID) REFERENCES SCHOOL (ID)
);

CREATE TABLE IF NOT EXISTS TEACHER (
    USER_ID   INT NOT NULL,
    SCHOOL_ID INT NOT NULL,
    PRIMARY KEY (USER_ID),
    FOREIGN KEY (USER_ID) REFERENCES USERS (ID),
    FOREIGN KEY (SCHOOL_ID) REFERENCES SCHOOL (ID)
);

CREATE TABLE IF NOT EXISTS CLASS_ENROLLMENT (
    ID              INT  GENERATED BY DEFAULT AS IDENTITY,
    STUDENT_ID      INT  NOT NULL,
    SCHOOL_CLASS_ID INT  NOT NULL,
    START_DATE      DATE NOT NULL,
    END_DATE        DATE DEFAULT NULL,
    PRIMARY KEY (ID),
    FOREIGN KEY (STUDENT_ID) REFERENCES STUDENT (USER_ID),
    FOREIGN KEY (SCHOOL_CLASS_ID) REFERENCES SCHOOL_CLASS (ID)
);

-- ---- 勤務先・シフト関連（学生は USERS.ID で持つ） ----

CREATE TABLE IF NOT EXISTS WORKPLACE (
    ID          INT         GENERATED BY DEFAULT AS IDENTITY,
    STUDENT_ID  INT         NOT NULL,
    NAME        VARCHAR(50) NOT NULL,
    BRANCH_NAME VARCHAR(50) DEFAULT NULL,
    COLOR       VARCHAR(7)  DEFAULT NULL,
    PRIMARY KEY (ID),
    FOREIGN KEY (STUDENT_ID) REFERENCES STUDENT (USER_ID)
);

CREATE TABLE IF NOT EXISTS SHIFT_TEMPLATE (
    ID           INT         GENERATED BY DEFAULT AS IDENTITY,
    WORKPLACE_ID INT         NOT NULL,
    NAME         VARCHAR(20) NOT NULL,
    START_TIME   TIME        NOT NULL,
    END_TIME     TIME        NOT NULL,
    BREAK_MIN    INT         NOT NULL DEFAULT 0,
    PRIMARY KEY (ID),
    FOREIGN KEY (WORKPLACE_ID) REFERENCES WORKPLACE (ID)
);

CREATE TABLE IF NOT EXISTS SHIFT (
    ID           INT         GENERATED BY DEFAULT AS IDENTITY,
    STUDENT_ID   INT         NOT NULL,
    WORKPLACE_ID INT         NOT NULL,
    WORK_DATE    DATE        NOT NULL,
    START_TIME   TIME        NOT NULL,
    END_TIME     TIME        NOT NULL,
    BREAK_START  TIME        DEFAULT NULL,
    BREAK_END    TIME        DEFAULT NULL,
    PRIMARY KEY (ID),
    FOREIGN KEY (STUDENT_ID) REFERENCES STUDENT (USER_ID),
    FOREIGN KEY (WORKPLACE_ID) REFERENCES WORKPLACE (ID)
);
